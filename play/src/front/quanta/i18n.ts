type Params = Record<string, string | number>;

function format(template: string, params?: Params): string {
    return params ? template.replace(/\{(\w+)(?::\w+)?\}/g, (_, key: string) => String(params[key] ?? "")) : template;
}

export const QL = derived(locale, ($locale) => {
    const strings: Strings = (dictionaries as Partial<Record<Locales, Strings>>)[$locale] ?? enUS;
    return Object.fromEntries(
        Object.entries(strings).map(([key, value]) => [key, (params?: Params) => format(value, params)]),
    ) as Record<keyof Strings, (params?: Params) => string>;
});
